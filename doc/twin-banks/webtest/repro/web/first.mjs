import { chromium } from '/usr/local/lib/node_modules/playwright/index.mjs';
const OUT = '/tmp/claude-0/-home-user/1f4c6304-ab2c-5e82-982d-3df83f263ee2/scratchpad/release/web';
const [w, h, tag, touch] = [Number(process.argv[2]), Number(process.argv[3]), process.argv[4], process.argv[5] === 'touch'];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const ctx = await b.newContext({ viewport: { width: w, height: h }, hasTouch: touch, isMobile: touch, deviceScaleFactor: touch ? 2 : 1 });
const p = await ctx.newPage();
const reqs = [];
p.on('request', (r) => reqs.push(r.url()));
p.on('console', (m) => { if (['error', 'warning'].includes(m.type())) console.log('console', m.type(), m.text().slice(0, 200)); });
p.on('pageerror', (e) => console.log('pageerror', e.message));
await p.goto('http://localhost:8766/');
await p.waitForTimeout(500);
await p.screenshot({ path: `${OUT}/${tag}-0boot.png` });
await p.waitForTimeout(5000);
await p.screenshot({ path: `${OUT}/${tag}-1who.png` });
console.log('TEXT1:', JSON.stringify(await p.evaluate(() => document.body.innerText.slice(0, 600))));
console.log('persisted?', await p.evaluate(async () => navigator.storage.persisted && await navigator.storage.persisted()));
console.log('estimate', JSON.stringify(await p.evaluate(async () => navigator.storage.estimate && await navigator.storage.estimate())));
console.log('cookies', JSON.stringify(await ctx.cookies()));
console.log('localStorage keys', JSON.stringify(await p.evaluate(() => Object.keys(localStorage))));
console.log('REQUESTS', [...new Set(reqs.map((u) => new URL(u).host))].join(' '), reqs.length);
await b.close();
