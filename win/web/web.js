// The sheet, the doll's letters and the menu pictures in the Colour vision
// setting's tile palette; protanopia and deuteranopia share one.
function applyTilePalette() {
  if (!sheetStd) return;
  const pairs = TILE_MODES[P.get('colourVision')] || null;
  if (pairs === sheetMode) return;
  sheetMode = pairs;
  // a newer switch outdates any picture still being encoded for this one
  const gen = ++sheetGen;
  tileCache.clear();
  dollCache.clear();
  const root = document.documentElement.style;
  // the pictures fall back to tiles.png until this mode's own sheet is ready
  root.removeProperty('--sheet');
  if (sheetUrl) { URL.revokeObjectURL(sheetUrl); sheetUrl = null; }
  if (!pairs) {
    setPalette(sheetPalette);
    sheet = sheetImg;
    sheetPx = sheetStd;
    return;
  }
  const map = new Map();
  for (let i = 0; i + 1 < pairs.length; i += 2) map.set(pairs[i], pairs[i + 1]);
  // Some browsers blur canvas readback a little against fingerprinting
  // (Brave's shields; Firefox's protection): a pixel within 2 of one of the
  // sheet's own colours is taken as that colour.  If many are near none, the
  // readback is not the sheet (Firefox's resistFingerprinting can return
  // random or all-white data), and the tiles stay as they are rather than
  // drawn from it.  All-white passes the first test, white being a sheet
  // colour, so the tile background must also be its usual share: 57% of the
  // sheet's pixels, so under a quarter means the readback is something else.
  const table = Object.values(sheetPalette).map((h) => parseInt(h.slice(1), 16));
  const background = parseInt(sheetPalette['.'].slice(1), 16);
  // An exact colour is itself, else the nearest within 2 on every channel:
  // the background #476c6c and the sheet's '1', #486c6c, are one step apart,
  // so the first colour within 2 would be the wrong one.
  const exact = new Set(table);
  const seen = new Map();
  const near = (rgb) => {
    if (exact.has(rgb)) return rgb;
    let v = seen.get(rgb);
    if (v !== undefined) return v;
    v = -1;
    let best = 7;
    for (const c of table) {
      const dr = Math.abs((c >> 16) - (rgb >> 16)), dg = Math.abs(((c >> 8) & 255) - ((rgb >> 8) & 255));
      const db = Math.abs((c & 255) - (rgb & 255));
      if (dr <= 2 && dg <= 2 && db <= 2 && dr + dg + db < best) { best = dr + dg + db; v = c; }
    }
    seen.set(rgb, v);
    return v;
  };
  const img = new ImageData(new Uint8ClampedArray(sheetStd.data), sheetStd.width, sheetStd.height), d = img.data;
  let opaque = 0, strange = 0, ground = 0;
  for (let i = 0; i < d.length; i += 4) {
    if (d[i + 3] !== 255) continue;
    opaque++;
    const std = near((d[i] << 16) | (d[i + 1] << 8) | d[i + 2]);
    if (std < 0) { strange++; continue; }
    if (std === background) ground++;
    const to = map.has(std) ? map.get(std) : std;
    d[i] = to >> 16; d[i + 1] = (to >> 8) & 255; d[i + 2] = to & 255;
  }
  // the sheet has no transparency, so a readback mostly transparent is not it
  if (opaque < d.length / 4 * 0.9 || strange > opaque / 100 || ground < opaque / 4) {
    console.warn(`tile palette: the canvas readback is not the tile sheet (${strange} of ${opaque} pixels match no `
      + `colour of it, ${ground} are its background); tiles left as they are`);
    setPalette(sheetPalette);
    sheet = sheetImg;
    sheetPx = sheetStd;
    return;
  }
  setPalette(sheetPalette, map);
  const c = document.createElement('canvas');
  c.width = img.width;
  c.height = img.height;
  c.getContext('2d').putImageData(img, 0, 0);
  sheet = c;
  sheetPx = img;
  // menu and creation pictures are CSS backgrounds (rolehack.css --sheet)
  c.toBlob((b) => {
    if (gen !== sheetGen || !b) return;
    if (sheetUrl) URL.revokeObjectURL(sheetUrl);
    sheetUrl = URL.createObjectURL(b);
    root.setProperty('--sheet', `url(${sheetUrl})`);
  });
}

// tile n as 256 0xRRGGBB pixels, the form the doll works in
function tilePx(n) {
  let px = tileCache.get(n);
  if (px) return px;
  px = new Int32Array(256);
  const ox = (n % sheetCols) * 16, oy = Math.floor(n / sheetCols) * 16, d = sheetPx.data;
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      const i = ((oy + y) * sheetPx.width + ox + x) * 4;
      px[y * 16 + x] = (d[i] << 16) | (d[i + 1] << 8) | d[i + 2];
    }
  }
  tileCache.set(n, px);
  return px;
}

