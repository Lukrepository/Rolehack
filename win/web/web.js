function form(title, fields, buttons) {
  const box = $('form');
  box.querySelector('.title').textContent = title;
  const body = box.querySelector('.body');
  body.innerHTML = '';
  const values = {};
  const f = document.createElement('div');
  f.className = 'form';
  const addField = (fd, into) => {
    // a group: rows in a box of their own, its name on the rim (Settings'
    // Accessibility, Lucas 2026-10-08); a fieldset, so a screen reader
    // announces the name as it enters the group
    if (fd.group) {
      const box = document.createElement('fieldset');
      box.className = 'group';
      const name = document.createElement('legend');
      name.textContent = fd.group;
      box.appendChild(name);
      for (const sub of fd.fields) addField(sub, box);
      into.appendChild(box);
      return;
    }
    if (fd.note) { const n = document.createElement('div'); n.className = 'note'; n.textContent = fd.note; into.appendChild(n); return; }
    if (fd.html) { const n = document.createElement('div'); n.className = 'note'; n.innerHTML = fd.html; into.appendChild(n); return; }
    const lab = document.createElement('label');
    lab.textContent = fd.label;
    if (fd.seg) {
      // a row of keycaps; the chosen one lit amber, as a mode toggle is
      values[fd.seg] = fd.value;
      const seg = document.createElement('div');
      seg.className = 'seg';
      for (const [val, text] of fd.options) {
        const b = capButton(text, { amber: val === fd.value, onTap: () => {
          values[fd.seg] = val;
          for (const o of seg.children) o.classList.toggle('amber', o === b);
          if (fd.onPick) fd.onPick(val, values);
        } });
        seg.appendChild(b);
      }
      // a <label> hands a click on its words, or on the gaps between the
      // keycaps, to its first button, which picked the first choice unseen
      lab.addEventListener('click', (e) => { if (!e.target.closest('button')) e.preventDefault(); });
      lab.appendChild(seg);
    } else if (fd.multiline) {
      const inp = document.createElement('textarea');
      inp.value = fd.value || '';
      inp.spellcheck = false;
      inp.rows = 4;
      // a line to read and copy, never to edit (the device report)
      if (fd.readonly) { inp.readOnly = true; inp.rows = 3; }
      inp.addEventListener('input', () => { values[fd.id] = inp.value; });
      // Enter makes a new line here; Esc still closes the form
      inp.addEventListener('keydown', (e) => { if (e.key !== 'Escape') e.stopPropagation(); });
      values[fd.id] = inp.value;
      lab.appendChild(inp);
    } else {
      const inp = document.createElement('input');
      inp.value = fd.value || '';
      inp.spellcheck = false;
      if (fd.numeric) inp.inputMode = 'numeric';
      inp.addEventListener('input', () => { values[fd.id] = inp.value; });
      inp.addEventListener('keydown', (e) => {
        if (e.key !== 'Enter') return;
        e.preventDefault();
        e.stopPropagation();
        done(primary);
      });
      values[fd.id] = inp.value;
      lab.appendChild(inp);
    }
    into.appendChild(lab);
  };
  for (const fd of fields) addField(fd, f);
  const primary = buttons.find((b) => b.primary);
  // touch only: a dialog with something to type in brings the keyboard up
  const touch = !!P.get('touchKeyboard') && !!f.querySelector('input');
  const done = (b, el) => {
    // a button that keeps the form open (Copy report): it gets the values, its
    // own keycap and the hint line to answer in
    if (b && b.stay) { if (b.run) b.run(values, el, box.querySelector('.hint')); return; }
    box.parentElement.hidden = true;
    formOpen = null;
    windowClosed();
    if (touch) showKeyboard(false);
    if (b && b.run) b.run(values);
  };
  box.querySelector('.caps').replaceChildren(...buttons.map((b) => {
    const el = capButton(b.label, { amber: !!b.primary, key: b.primary ? 'Enter' : '', onTap: () => done(b, el) });
    return el;
  }));
  box.querySelector('.hint').textContent = 'Esc closes';
  body.appendChild(f);
  box.parentElement.hidden = false;
  body.scrollTop = 0;
  formOpen = { cancel: () => done(null), accept: () => done(primary) };
  if (touch) {
    for (const inp of f.querySelectorAll('input')) inp.inputMode = 'none';
    showKeyboard(true);
  }
  const first = f.querySelector('input');
  if (first) first.focus();
}

